export function formatCityName(name, state) {
  return `${name} - ${state}`;
}

function normalizeCity(value) {
  return String(value || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/\s*[-–—]\s*/g, " ")
    .replace(/\s+/g, " ")
    .replace(/\bsao\b/gi, "sao")
    .toLowerCase()
    .trim();
}

function canonicalBrazilianCityName(name, state) {
  const cleanedName = String(name || "").trim();
  const cleanedState = String(state || "").trim();
  if (!cleanedName || !cleanedState) return null;

  const formatted = `${cleanedName} - ${cleanedState}`;
  return formatted
    .replace(/\s{2,}/g, " ")
    .trim();
}

// Aceita "Cidade - País" ou "Cidade - Estado/Província - País" para destinos
// fora do Brasil. A existência real da cidade é confirmada depois pelo
// backend via geocodificação (Nominatim) antes de salvar a viagem.
function formatInternationalCity(value) {
  const raw = String(value || "").trim();
  if (!raw) return null;

  if (raw.includes(",")) return null;

  const parts = raw
    .split("-")
    .map((p) => p.trim())
    .filter(Boolean);

  if (parts.length < 2 || parts.length > 3) return null;
  if (parts.some((p) => p.length < 2 || /^\d+$/.test(p))) return null;

  const addressTokens = /\b(rua|avenida|av|av\.|travessa|tv|rodovia|br|estrada|bairro|jardim|parque|plaza|praca|casa|predio|edificio|lote|quadra|setor|s\/n|sn|km)\b/i;
  if (addressTokens.test(parts[0])) return null;

  if (parts.length === 2) {
    const last = parts[1];
    if (/^[A-Z]{2}$/.test(last)) return null;
  }

  return parts.join(" - ");
}

export function findCity(value) {
  const raw = String(value || "").trim();
  if (!raw || /^\d+$/.test(raw)) return null;

  const normalized = normalizeCity(raw);
  if (!normalized) return null;

  for (const [name, state] of BR_CITIES) {
    const city = canonicalBrazilianCityName(name, state);
    if (city && normalizeCity(city) === normalized) return city;
  }

  const international = formatInternationalCity(raw);
  if (international) return international;

  return null;
}

export function searchCities(query, max = 8) {
  if (!query) return [];
  const q = String(query).normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().trim();
  if (!q) return [];
  const matches = [];
  const starts = [];
  const mid = [];
  for (const [name, state] of BR_CITIES) {
    const full = formatCityName(name, state);
    const norm = full.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
    if (norm === q) {
      matches.unshift(full);
    } else if (norm.startsWith(q)) {
      starts.push(full);
    } else if (norm.includes(q)) {
      mid.push(full);
    }
  }
  const result = [...matches, ...starts, ...mid];
  return result.slice(0, max);
}
